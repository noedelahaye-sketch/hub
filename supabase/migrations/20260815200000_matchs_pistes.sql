-- Le prochain match des pistes (idée de Noé, 15 août 2026) : « c'est le
-- calendrier des matchs qui décide de la fournée » — alors le calendrier vient
-- à l'écran. Les appariements d'une saison sont publics et figés dès l'été :
-- l'ADVERSAIRE et le NUMÉRO DE JOURNÉE ne bougent plus, seule l'heure exacte
-- glisse avec la télévision. La date stockée est donc un repère, pas une
-- convocation — et c'est la tolérance que Noé a lui-même posée.
--
-- Une ligne = un match VU PAR UNE PISTE (dénormalisé, deux lignes par match
-- quand les deux clubs sont au vivier) : la question du site est toujours
-- « quel est le prochain match de CE club ? », jamais « quel est le programme
-- de la journée ? ». Chargé une fois par saison depuis les calendriers
-- publics (fbref.com) ; à re-synchroniser à l'occasion si les reports
-- s'accumulent.
--
-- Cette migration charge la Ligue 1 2026-2027 (306 matchs, 612 lignes) —
-- l'échantillon à valider ; les sept autres championnats suivront.

create table public.matchs_pistes (
  id uuid primary key default gen_random_uuid(),
  piste_id uuid not null references public.pistes(id) on delete cascade,
  journee int not null,
  date date not null,
  adversaire text not null,
  domicile boolean not null,
  created_at timestamptz not null default now()
);

comment on table public.matchs_pistes is
  'Le calendrier des clubs du vivier, une ligne par match et par piste. Chargé par saison, dates indicatives.';
comment on column public.matchs_pistes.adversaire is
  'Le nom de l''adversaire, tel qu''il s''affiche. Pas de lien : il peut ne pas être au vivier.';
comment on column public.matchs_pistes.domicile is
  'true = la piste reçoit ; false = elle se déplace.';

create index matchs_pistes_piste_date_idx on public.matchs_pistes (piste_id, date);

alter table public.matchs_pistes enable row level security;

create policy "matchs_pistes_select_authenticated" on public.matchs_pistes
  for select to authenticated using (true);
create policy "matchs_pistes_insert_authenticated" on public.matchs_pistes
  for insert to authenticated with check (true);
create policy "matchs_pistes_update_authenticated" on public.matchs_pistes
  for update to authenticated using (true) with check (true);
create policy "matchs_pistes_delete_authenticated" on public.matchs_pistes
  for delete to authenticated using (true);

grant select, insert, update, delete on public.matchs_pistes to authenticated;

-- La vue que lit le site : LE prochain match de chaque piste, 97 lignes au
-- plus — jamais les 600 et quelques de la table. `security_invoker` pour que
-- la RLS de la table s'applique au lecteur, pas au propriétaire de la vue.
create view public.prochain_match_par_piste
with (security_invoker = true) as
  select distinct on (piste_id) piste_id, journee, date, adversaire, domicile
  from public.matchs_pistes
  where date >= current_date
  order by piste_id, date;

grant select on public.prochain_match_par_piste to authenticated;

